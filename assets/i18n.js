  var LANG_KEY = 'tqr_lang';
  var supported = ['uk', 'en'];
  var memoryLang = null;

  function store(lang) {
    try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* приватний режим */ }
    memoryLang = lang;
  }
  function load() {
    try { return localStorage.getItem(LANG_KEY); } catch (e) { return memoryLang; }
    return memoryLang;
  }

  function detect() {
    var stored = load();
    if (stored && supported.indexOf(stored) !== -1) return stored;
    var nav = (navigator.language || 'uk').toLowerCase();
    if (nav.indexOf('uk') !== -1) return 'uk';
    return 'en';
  }

  function t(lang, key) {
    var v = dict[lang] ? dict[lang][key] : dict.en[key];
    return v === undefined ? key : v;
  }

  function product(lang, id) {
    return (dict[lang] || dict.en).products[id] || (dict.en).products[id];
  }

  function apply(lang) {
    document.documentElement.lang = lang;
    store(lang);
    var nodes = document.querySelectorAll('[data-i18n], [data-i18n-html]');
    for (var i = 0; i < nodes.length; i++) {
      var key = nodes[i].getAttribute('data-i18n') || nodes[i].getAttribute('data-i18n-html');
      var val = t(lang, key);
      if (nodes[i].hasAttribute('data-i18n-html')) nodes[i].innerHTML = val;
      else nodes[i].textContent = val;
    }
    var ph = document.querySelectorAll('[data-i18n-ph]');
    for (var j = 0; j < ph.length; j++) ph[j].setAttribute('placeholder', t(lang, ph[j].getAttribute('data-i18n-ph')));
    var btns = document.querySelectorAll('.lang-btn');
    for (var k = 0; k < btns.length; k++) btns[k].classList.toggle('active', btns[k].getAttribute('data-lang') === lang);
    document.dispatchEvent(new CustomEvent('tqr:lang', { detail: lang }));
  }

  function init() {
    var lang = detect();
    var btns = document.querySelectorAll('.lang-btn');
    for (var i = 0; i < btns.length; i++) {
      btns[i].addEventListener('click', function () { apply(this.getAttribute('data-lang')); });
    }
    apply(lang);
    return lang;
  }

  return { init: init, apply: apply, t: t, product: product, detect: detect };
